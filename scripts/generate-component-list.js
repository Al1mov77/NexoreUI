const fs = require('fs');
const path = require('path');

const registryDir = path.resolve(__dirname, '../packages/cli/src/registry');
const outputFile = path.resolve(__dirname, '../apps/docs/lib/registry/component-list.generated.ts');

const files = fs.readdirSync(registryDir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts' && !f.startsWith('template-'))
  .sort();

function toLabel(id) {
  const specialMap = {
    'ai-prompt-input': 'AI Prompt Input',
    'aurora-border-card': 'Aurora Border Card',
    'aurora-border-fx': 'Aurora Border FX',
    'aurora-search-pill': 'Aurora Search Pill',
    'blur-fade': 'Blur Fade',
    'dark-mode': 'Theme Toggle',
    'data-display': 'Data Display',
    'file-upload': 'File Upload',
    'frost-hover-card': 'Frost Hover Card',
    'glass-shatter-card': 'Glass Shatter Card',
    'holo-finish-card': 'Holo Finish Card',
    'interactive-code-block': 'Code Block',
    'live-object': 'Live 3D Object',
    'morphing-geometry': 'Morphing Geometry',
    'node-flow-graph': 'Node Flow Graph',
    'number-ticker': 'Number Ticker',
    'particle-reveal-card': 'Particle Reveal Card',
    'premium-charts': 'Charts',
    'premium-commerce': 'Commerce',
    'premium-effects': 'Spotlight & Grid Effects',
    'premium-media': 'Media & Audio',
    'premium-overlays': 'Overlays & Drawers',
    'premium-social': 'Social & Chat',
    'pro-buttons': 'Action Buttons',
    'pro-cards': '3D Product Cards',
    'pro-inputs': 'Specialized Inputs',
    'pro-objects': '3D Objects Bundle',
    'scroll-area': 'Scroll Area',
    'silk-unveil': 'SilkUnveil',
    'sound-pulse': 'SoundPulse',
    'special-animations': 'Motion Primitives',
    'special-forms': 'Form Controls',
    'ultra-components': 'Atmospheric Effects',
    'ultra-effects': 'Text & Motion Effects',
  };

  if (specialMap[id]) return specialMap[id];
  return id
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}

function getCategory(id) {
  if (id.startsWith('ai-') || id === 'node-flow-graph' || id === 'command' || id === 'interactive-code-block') {
    return 'ai';
  }
  if (
    id === 'button' ||
    id === 'pro-buttons' ||
    id === 'input' ||
    id === 'pro-inputs' ||
    id === 'special-forms' ||
    id === 'checkbox' ||
    id === 'switch' ||
    id === 'slider' ||
    id === 'select' ||
    id === 'rating' ||
    id === 'file-upload'
  ) {
    return 'forms';
  }
  if (
    id === 'frost-hover-card' ||
    id === 'glass-shatter-card' ||
    id === 'holo-finish-card' ||
    id === 'particle-reveal-card' ||
    id === 'card' ||
    id === 'aurora-border-card' ||
    id === 'pro-cards'
  ) {
    return 'cards';
  }
  if (
    id === 'accordion' ||
    id === 'tabs' ||
    id === 'table' ||
    id === 'stepper' ||
    id === 'scroll-area' ||
    id === 'navigation' ||
    id === 'dock' ||
    id === 'data-display' ||
    id === 'premium-charts' ||
    id === 'premium-commerce' ||
    id === 'premium-media'
  ) {
    return 'layout';
  }
  if (
    id === 'dialog' ||
    id === 'premium-overlays' ||
    id === 'alert' ||
    id === 'badge' ||
    id === 'avatar' ||
    id === 'tooltip' ||
    id === 'progress' ||
    id === 'skeleton' ||
    id === 'loader' ||
    id === 'toaster' ||
    id === 'premium-social' ||
    id === 'dark-mode'
  ) {
    return 'feedback';
  }
  if (
    id === 'glass-lens' ||
    id === 'fluted-glass' ||
    id === 'ripple-water' ||
    id === 'scroll-warp' ||
    id === 'twist-ribbon' ||
    id === 'dither-image' ||
    id === 'gravity-grid' ||
    id === 'scroll-drum' ||
    id === 'liquid-smear' ||
    id === 'type-proximity' ||
    id === 'holo-foil' ||
    id === 'letter-pile' ||
    id === 'flow-field' ||
    id === 'text-rail' ||
    id === 'moire-grating' ||
    id === 'swipe-deck' ||
    id === 'camera-mirror' ||
    id === 'scroll-reveal'
  ) {
    return 'shaders';
  }
  return 'effects';
}

const components = files.map((f) => {
  const id = f.replace('.ts', '');
  return {
    id,
    name: toLabel(id),
    category: getCategory(id),
    tier: 'free',
  };
});

const fileContent = `/**
 * AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.
 * Generated by scripts/generate-component-list.js
 * Source of truth: packages/cli/src/registry/
 */

export interface RegistryComponentItem {
  id: string;
  name: string;
  category: "ai" | "forms" | "cards" | "layout" | "feedback" | "effects" | "shaders";
  tier: "free";
}

export const REGISTRY_COMPONENTS: readonly RegistryComponentItem[] = ${JSON.stringify(components, null, 2)} as const;

export const ALL_COMPONENT_IDS: readonly string[] = REGISTRY_COMPONENTS.map((c) => c.id);

export const TOTAL_REGISTRY_COMPONENTS_COUNT = ${components.length};
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, fileContent, 'utf8');

console.log(`Generated component list: ${components.length} free components written to ${path.relative(process.cwd(), outputFile)}`);
